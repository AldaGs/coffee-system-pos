// New-online-order alerts (schema 4.0): Telegram via the shop's own bot and
// Web Push to the devices that opted in. Delivery runs server-side in the
// "order-alert" Edge Function, so it works with no TinyPOS open anywhere.
import { supabase } from '../supabaseClient';

const b64u = (buf) => btoa(String.fromCharCode(...new Uint8Array(buf))).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
const unb64u = (s) => Uint8Array.from(atob(s.replace(/-/g, '+').replace(/_/g, '/') + '==='.slice((s.length + 3) % 4)), (c) => c.charCodeAt(0));

const hookUrl = () => `${(localStorage.getItem('tinypos_supabase_url') || import.meta.env.VITE_SUPABASE_URL || '').replace(/\/+$/, '')}/functions/v1/order-alert`;

export async function loadAlertStatus() {
  const { data, error } = await supabase.rpc('order_alerts_status');
  if (error) throw error;
  return data;
}

export async function saveAlertSettings({ enabled, telegramToken = '', clearChats = false }) {
  const { error } = await supabase.rpc('set_order_alerts', {
    p_enabled: enabled, p_hook_url: hookUrl(), p_telegram_token: telegramToken, p_clear_chats: clearChats,
  });
  if (error) throw error;
}

async function invoke(action) {
  const { data, error } = await supabase.functions.invoke('order-alert', { body: { action } });
  if (error) {
    const body = await error.context?.json?.().catch(() => null);
    throw new Error(body?.error || error.message);
  }
  return data;
}
export const detectTelegramChats = () => invoke('telegram_detect');
export const sendTestAlert = () => invoke('test');

export const pushSupported = () => typeof window !== 'undefined' && 'serviceWorker' in navigator && 'PushManager' in window && 'Notification' in window;

async function currentSubscription() {
  if (!pushSupported()) return null;
  const reg = await navigator.serviceWorker.ready;
  return reg.pushManager.getSubscription();
}
export const isPushOnHere = async () => !!(await currentSubscription().catch(() => null));

// Shop-wide VAPID pair, generated by the first device that enables push.
async function vapidPublicKey(status) {
  if (status?.vapid_public) return status.vapid_public;
  const kp = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign']);
  const pub = b64u(await crypto.subtle.exportKey('raw', kp.publicKey));
  const priv = (await crypto.subtle.exportKey('jwk', kp.privateKey)).d;
  const { data, error } = await supabase.rpc('init_vapid_keys', { p_public: pub, p_private: priv });
  if (error) throw error;
  return data;
}

export async function enablePushHere(status) {
  if (!pushSupported()) throw new Error('unsupported');
  if (await Notification.requestPermission() !== 'granted') throw new Error('denied');
  const key = await vapidPublicKey(status);
  const reg = await navigator.serviceWorker.ready;
  let sub = await reg.pushManager.getSubscription();
  // A subscription made under another key (e.g. a reinstalled project) can't be reused.
  const same = sub?.options?.applicationServerKey && b64u(sub.options.applicationServerKey) === key;
  if (sub && !same) { await sub.unsubscribe(); sub = null; }
  if (!sub) sub = await reg.pushManager.subscribe({ userVisibleOnly: true, applicationServerKey: unb64u(key) });
  const { endpoint, keys } = sub.toJSON();
  const { error } = await supabase.rpc('save_push_subscription', {
    p_endpoint: endpoint, p_p256dh: keys.p256dh, p_auth: keys.auth, p_label: navigator.userAgent,
  });
  if (error) throw error;
}

export async function disablePushHere() {
  const sub = await currentSubscription();
  if (!sub) return;
  await supabase.rpc('delete_push_subscription', { p_endpoint: sub.endpoint });
  await sub.unsubscribe();
}
